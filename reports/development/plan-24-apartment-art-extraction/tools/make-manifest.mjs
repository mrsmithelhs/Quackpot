// Authoring tool (NOT runtime): writes extraction-manifest.md, mapping every extracted symbol of the frozen Plan 10
// baseline to its new module/export. Line ranges are computed from the verified frozen preview.html blob.
// Usage (repo root): node reports/development/plan-24-apartment-art-extraction/tools/make-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';
import { loadBaseline, FROZEN, REPO_ROOT } from './baseline.mjs';

const { lines } = loadBaseline();
const start = lines.findIndex(l => l.startsWith('  let svgInstance = 0;')), end = lines.findIndex(l => l.startsWith('  function update() {'));
const stmts = {};
let cur = null;
for (let i = start; i < end; i++) {
  const m = lines[i].match(/^  (?:const|function) ([A-Za-z_$][\w$]*)/);
  if (m) { cur = { from: i + 1, to: i + 1 }; stmts[m[1]] = cur; }
  else if (cur && !(lines[i].trim() === '' || lines[i].trim().startsWith('//'))) cur.to = i + 1; else cur = null;
}
const range = n => (stmts[n] ? `${stmts[n].from}${stmts[n].to > stmts[n].from ? `–${stmts[n].to}` : ''}` : '—');

const rows = [];
const add = (symbol, where, target, method, check, note = '') => rows.push(`| \`${symbol}\` | ${where} | ${target} | ${method} | ${check} | ${note} |`);
const SCRIPT = 'script (`extract-verbatim.mjs`)', WORKER = 'Haiku worker, Sonnet-verified', SONNET = 'Sonnet';
add('views', '`duck-views.js` whole file (five duck views)', '`duck/views.mjs` → `views`', SCRIPT, 'deep-equal + byte-identical body', 'header comment added');
add('topDuckInner', `preview ${range('topDuckInner')}`, '`duck/overhead.mjs` → `topDuckInner`', SCRIPT, 'string equal');
for (const n of ['PX_MM', 'PHONE_MM', 'DUCK_SCALE', 'DUCK_CX', 'F', 'CX', 'DUCK_UNITS_PER_MM']) add(n, `preview ${range(['CX', 'DUCK_UNITS_PER_MM'].includes(n) ? 'F' : n)}`, `\`core/constants.mjs\` → \`${n}\``, SCRIPT, 'value equal', n === 'F' ? '`F`, `CX`, `DUCK_UNITS_PER_MM` share one source line' : '');
add('sceneDefs', `preview ${range('sceneDefs')}`, '`lighting/defs.mjs` → `sceneDefs`', SCRIPT, 'string equal');
const FAMILY = {
  prims: ['R', 'Ci', 'El', 'Pg', 'Pa', 'NS', 'sc_'], decor: ['art', 'windowMm', 'plant', 'mug', 'magazines', 'clock', 'clockSmall'], living: ['sofa', 'coffeeTable', 'tvUnit', 'floorLamp'],
  kitchen: ['fridge', 'cabinetRun', 'stove', 'pot', 'hood', 'upperCabs', 'kettle', 'toaster', 'jars', 'bar', 'stool', 'fruit', 'pendant'], bedroom: ['bed', 'bedside', 'bedLamp'], toys: ['toyShelf', 'teddy', 'block', 'robot', 'truck', 'rings', 'ball', 'bunny']
};
for (const [fam, names] of Object.entries(FAMILY)) for (const n of names) add(n, `preview ${range(n)}`, `\`props/${fam}.mjs\` → \`${n}\``, SCRIPT, 'output equal for sampled arguments');
add('proj, put', `preview ${range('proj')}, ${range('put')}`, '`rooms/camera.mjs`', WORKER, 'output equal');
add('ROOM_SPECS', `preview ${range('ROOM_SPECS')}`, '`rooms/specs.mjs` → `ROOM_SPECS`', WORKER, 'via room scenes', 'living `items(sold)` → `items({ couch, tv })`');
add('roomScene', `preview ${range('roomScene')}`, '`rooms/scene.mjs` → `buildRoomScene`', WORKER, 'normalised-id equal, every room/framing/duck view + sold living', 'signature, validation, no `uniq`');
add('phoneFace', `preview ${range('phoneFace')}`, '`desk/phone.mjs` → `phoneFace`, `DEFAULT_PHONE_TEXT`', WORKER, 'default copy byte-equal', 'text parameterised, escaped, empty lines omitted');
add('sideDeskScene', `preview ${range('sideDeskScene')}`, '`desk/side.mjs` → `buildSideDeskScene`', WORKER, 'normalised-id equal, three duck views', 'no `uniq`; phone argument');
add('topDeskScene', `preview ${range('topDeskScene')}`, '`desk/top.mjs` → `buildTopDeskScene`', WORKER, 'normalised-id equal', 'no `uniq`; phone argument');
add('inner', `preview ${range('inner')}`, '`core/svg.mjs` → `inner`', SONNET, 'used by every scene (indirect)');
add('uniq, renderViewSvg', `preview ${range('uniq')}, ${range('renderViewSvg')}`, '`core/ids.mjs` → `scopeIds` (replacement)', SONNET, 'interface tests (unique ids, resolvable refs)', 'counter-based suffix replaced by a required caller prefix');

const out = `# Plan 24 extraction manifest

Generated by \`tools/make-manifest.mjs\` from the verified frozen baseline: repo commit \`${FROZEN.commit}\`, \`preview.html\` blob \`${FROZEN.preview.blob}\`, \`duck-views.js\` blob \`${FROZEN.duckViews.blob}\`. Line numbers refer to that frozen \`preview.html\` (529 lines). All modules live in \`src/assets/apartment/\`; nothing there imports a report.

## Source → module

| Original symbol | Frozen location | New module / export | Method | Fidelity check (\`tools/fidelity-check.mjs\`) | Notes |
|---|---|---|---|---|---|
${rows.join('\n')}

## New code with no baseline counterpart

| Module | Role | Author |
|---|---|---|
| \`index.mjs\` | public API: \`renderDuck\`, \`renderScene\`, validation, option reporting, id scoping, light baking | Sonnet |
| \`core/ids.mjs\` | \`idPrefix\` validation, \`scopeIds\` | Sonnet |
| \`core/svg.mjs\` | \`escapeXml\`, \`checkText\` (bounded, XML-safe text) | Sonnet |
| \`duck/index.mjs\` | six-view registry, \`duckSvg\` (adds a thin standalone wrapper for the overhead drawing), \`resolveDuckView\` (explicit fallback metadata) | Sonnet |
| \`lighting/modes.mjs\` | page CSS re-expressed as scoped \`<style>\` with the mode baked in; in-SVG overlay equivalent of the original HTML overlay | Sonnet |
| \`props/index.mjs\` | re-export barrel | Sonnet |
| \`apartment.test.mjs\` | interface tests | Sonnet |

## Intentional differences from the baseline (each to be measured in the rendered comparison)

1. **Light baking:** page CSS \`.stage[data-light]\` became a per-scene scoped \`<style>\`; no 0.2 s fade; the dimming/tint overlay is drawn inside the SVG in scene coordinates, so it follows the scene box rather than the host stage's percentages. The warm pool's CSS gradient (premultiplied-alpha interpolation) is sampled into 17 SVG stops (\`premultipliedStops\`) because SVG gradients interpolate straight colour. Measured in the rendered comparison: see \`progress.md\`.
2. **Furnishings:** the living room takes independent \`couch\`/\`tv\` visibility flags; both-present and both-removed equal the baseline, mixed states are derived and unbaselined.
3. **Phone copy:** bounded, escaped strings with baseline defaults.
4. **IDs:** one required caller prefix instead of an instance counter.
5. **Standalone overhead duck:** a thin \`<svg>\` wrapper around the same drawing used by the top-down desk.
6. **Not extracted (review-app code):** the page controls, \`update()\`, view/shot/area/light label maps, the candidate comparison grid and the page-level CSS (the scene-relevant rules are in \`lighting/modes.mjs\`).
`;
fs.writeFileSync(path.join(REPO_ROOT, 'reports/development/plan-24-apartment-art-extraction/extraction-manifest.md'), out);
console.log('manifest rows:', rows.length);
